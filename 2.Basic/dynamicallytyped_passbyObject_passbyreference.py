# What is a dynamically typed language?
#       the data type of a variable is determined at runtime, not at compile time.
#       No need to declare data types manually
#       e.g., Python, JavaScript.
 

# Python’s argument-passing model is neither “Pass by Value” nor “Pass by Reference” but it is “Pass by Object Reference”.
#   Mutable objects (such as lists and dictionaries) can be modified inside a function.
#   Immutable objects (such as integers, strings and tuples) cannot be changed in place. 